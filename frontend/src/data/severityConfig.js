// Generate realistic 48-hour time series trend data for a ward
const generateTimeSeries = (baseRain, baseMoisture, isHighRisk) => {
  const points = [];
  const now = new Date();
  
  for (let i = 48; i >= 0; i--) {
    const time = new Date(now.getTime() - i * 60 * 60 * 1000);
    const timeStr = time.toLocaleTimeString('en-IN', { hour: '2-digit', minute: '2-digit', hour12: false });
    const dateStr = time.toLocaleDateString('en-IN', { month: 'short', day: 'numeric' });
    
    // Simulate storm curve peaking in last 12 hours if high risk
    let rainFactor = Math.sin((48 - i) / 8) * 0.5 + 0.5;
    if (i < 18 && isHighRisk) rainFactor *= 2.8;
    
    const rain1h = Math.max(0, Math.round((baseRain / 24) * rainFactor * (0.8 + Math.random() * 0.4) * 10) / 10);
    
    // Soil moisture increases cumulatively with rain
    const cumulativeFactor = Math.min(1, (48 - i) / 36);
    const moisture = Math.min(98, Math.round((baseMoisture * 0.6 + baseMoisture * 0.4 * cumulativeFactor + Math.random() * 2) * 10) / 10);
    
    points.push({
      timestamp: `${dateStr} ${timeStr}`,
      hourOffset: -i,
      rain1h: rain1h,
      soilMoisture: moisture,
      criticalThreshold: 85, // 85% Soil Saturation
      warningThreshold: 70,  // 70% Soil Saturation
      rainThreshold: 15,     // 15mm/h Heavy Rain Line
    });
  }
  return points;
};

